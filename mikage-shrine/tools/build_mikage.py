#!/usr/bin/env python3
"""Reproducibly externalize the original Mikage card's embedded assets.

Only data URLs are replaced. Game rules, art geometry, and script bodies are
otherwise preserved verbatim. This tool performs no network or Git operations.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import re
from pathlib import Path
from urllib.parse import urlparse


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CARD = ROOT / "upload/巴卫_御影神社_街区漫游_v1.7.0_重打包.json"
DEFAULT_MANIFEST = ROOT / "assets-audit/asset-manifest.json"
DEFAULT_OUTPUT = ROOT / "mikage-repo/mikage-shrine/runtime"
DEFAULT_BASE = (
    "https://cdn.jsdelivr.net/gh/AliceNekoqqq/"
    "Aliceneko-Map-Plugin@{commit}/mikage-shrine/"
)
DATA_URL = re.compile(r"data:([^;,]+)(?:;[^,]*)?;base64,([A-Za-z0-9+/=]+)")
SCRIPT_IDS = ("mvu", "panels", "scene")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--asset-commit", required=True,
                        help="Full 40-character Git commit containing the assets")
    parser.add_argument("--asset-base", default=DEFAULT_BASE,
                        help="HTTPS URL prefix template containing {commit}")
    parser.add_argument("--card", type=Path, default=DEFAULT_CARD)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    return parser.parse_args()


def build(args: argparse.Namespace) -> dict:
    if not re.fullmatch(r"[0-9a-fA-F]{40}", args.asset_commit):
        raise ValueError("--asset-commit must be a full 40-character Git SHA")
    if "{commit}" not in args.asset_base:
        raise ValueError("--asset-base must contain {commit}")
    asset_base = args.asset_base.replace("{commit}", args.asset_commit.lower())
    if urlparse(asset_base).scheme != "https" or not asset_base.endswith("/"):
        raise ValueError("--asset-base must be an absolute HTTPS URL ending in /")

    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    by_hash: dict[str, str] = {}
    for entry in manifest:
        digest, relative = entry["sha256"], entry["path"]
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise ValueError(f"Invalid manifest digest: {digest}")
        if not relative.startswith("assets/") or any(
            part in ("", ".", "..") for part in relative.split("/")
        ) or any(character in relative for character in "\\\"'`?#\n\r"):
            raise ValueError(f"Unsafe manifest path: {relative}")
        if digest in by_hash and by_hash[digest] != relative:
            raise ValueError(f"Ambiguous manifest digest: {digest}")
        by_hash[digest] = relative

    card = json.loads(args.card.read_text(encoding="utf-8"))
    scripts = card["data"]["extensions"]["tavern_helper"]["scripts"]
    if len(scripts) != len(SCRIPT_IDS):
        raise ValueError(f"Expected three original scripts, got {len(scripts)}")

    outputs = []
    used_hashes: set[str] = set()
    prepared = []
    for script_id, script in zip(SCRIPT_IDS, scripts):
        source = script["content"]
        count = 0

        def externalize(match: re.Match) -> str:
            nonlocal count
            binary = base64.b64decode(match.group(2), validate=True)
            digest = hashlib.sha256(binary).hexdigest()
            if digest not in by_hash:
                raise ValueError(f"Unmapped embedded asset in {script_id}: {digest}")
            used_hashes.add(digest)
            count += 1
            return asset_base + by_hash[digest]

        body = DATA_URL.sub(externalize, source)
        if re.search(r"data:[^\s\"'`<>]*;base64,", body, re.IGNORECASE):
            raise ValueError(f"Unconverted data URL remains in {script_id}")
        module = (
            "// Generated by build_mikage.py; edit the source, then rebuild.\n"
            "export const protocol = 1;\n"
            "export const version = '1.7.1';\n"
            f"export const scriptId = '{script_id}';\n"
            "export const VERSION = version;\n"
            "export const SCRIPT_ID = scriptId;\n"
            "export function start() {\n"
            + body
            + "\n}\n"
        )
        encoded = module.encode("utf-8")
        prepared.append((script_id + ".mjs", encoded))
        outputs.append({
            "file": script_id + ".mjs",
            "replacedDataUrls": count,
            "bytes": len(encoded),
            "sha256": hashlib.sha256(encoded).hexdigest(),
        })

    unused = set(by_hash) - used_hashes
    if unused:
        raise ValueError(f"Manifest contains {len(unused)} unreferenced assets")
    # Validate every source before creating or replacing any output.
    args.output.mkdir(parents=True, exist_ok=True)
    for filename, encoded in prepared:
        (args.output / filename).write_bytes(encoded)
    return {
        "assetCommit": args.asset_commit.lower(),
        "assetBase": asset_base,
        "uniqueAssets": len(used_hashes),
        "scripts": outputs,
    }


def main() -> None:
    args = parse_args()
    try:
        report = build(args)
    except (ValueError, KeyError, OSError) as error:
        raise SystemExit(f"Build failed: {error}") from error
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
