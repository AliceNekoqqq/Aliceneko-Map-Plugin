assert.equal(presentationView(state,'瑞希说：“我替巴卫回答。”').speaker,'本轮正文');
assert.equal(presentationView({...state,巴卫:{位置:'远处'}},'巴卫：“站近些。”').portrait,false);
assert.equal(presentationView({...state,巴卫:{位置:'廊'}},'正文').portrait,false);
assert.equal(presentationView(state,'').portrait,false);
assert.equal(presentationView(state,'正文').portrait,true);
assert.equal(presentationView(state,'字'.repeat(10000)).preview.length,191);
assert.equal(presentationView(state,'正文').taskText,'暂未接下委托');
assert.equal(JSON.stringify(state),original);
const newer=JSON.parse(await readFile(new URL('../releases/1.49.29/card-source.json',import.meta.url)));
assert.deepEqual(newer.data.character_book.entries,source.data.character_book.entries);
assert.deepEqual(newer.data.extensions.regex_scripts,source.data.extensions.regex_scripts);
const prev=JSON.parse(await readFile(new URL('../releases/1.49.28/manifest.json',import.meta.url)));
const next=JSON.parse(await readFile(new URL('../releases/1.49.29/manifest.json',import.meta.url)));
for(const m of prev.modules.filter(m=>m.module_id!=='scene')) assert.deepEqual(next.modules.find(x=>x.module_id===m.module_id),m);
assert(newer.data.extensions.tavern_helper.scripts.every(s=>s.content===''));
