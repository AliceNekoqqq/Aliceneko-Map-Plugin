import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {presentationView,narrativeText} from '../src/scene-presentation-core.mjs';
const source=JSON.parse(await readFile(new URL('../releases/1.49.28/card-source.json',import.meta.url)));
const state=JSON.parse(source.data.character_book.entries.find(e=>e.comment.includes('[InitVar]')).content);
const original=JSON.stringify(state);
assert.equal(narrativeText('前文\n<UpdateVariable>隐私</UpdateVariable>\n正文<StatusPlaceHolderImpl/>\n<MikageTaskArchive>内部'), '前文\n\n正文');
assert.equal(narrativeText('<think>hidden</think>\n<script>evil()</script>真实正文'), '真实正文');
